@pytest.fixture
def batched_copy():
    # Execute the generated byte descriptors against real CPU tensor storage.
    # Native NPU/VMM execution is covered by the hardware integration test.
    def copy(src, dst, sizes, **kwargs):
        for source, destination, size in zip(src.reshape(-1), dst.reshape(-1), sizes.reshape(-1)):
            if int(size):
                ctypes.memmove(int(destination), int(source), int(size))

    with patch.object(manager_module, "batch_memcpy_kernel") as kernel:
        kernel.__getitem__.return_value.side_effect = copy
        yield kernel


@pytest.mark.parametrize("computed", [0, 128, 129])
def test_fresh_dense_request_restores_local_views(computed, batched_copy):
    result = manager()
    with patch.object(manager_module.offload, "sparse_copy") as memfabric:
        result.dense_fill_copy_sfa_rows({1: (0, computed)}, block_size=128, block_table=np.array([[2, 0, 1]]))
    expected = torch.cat((result.k_caches_cpu[0][2], result.k_caches_cpu[0][0]))[:computed]
    torch.testing.assert_close(result.topk_buffers_k[0][1, :computed], expected)
    assert not result.topk_buffers_k[0][1, computed:].count_nonzero()
    memfabric.assert_not_called()
    assert batched_copy.__getitem__.return_value.call_count == int(computed > 0)


